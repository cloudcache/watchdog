func TestDecoderGoFlow2NetFlowV9WireFixture(t *testing.T) {
	assertFixtureSHA256(t, netFlowV9GoFlow2TemplateFixture, "81bf3c32b4c677c51d5b1874825f127edf587c92e70efc34edc236891368a610")
	assertFixtureSHA256(t, netFlowV9GoFlow2DataFixture, "06c18e9122ceea1fcef4cf62f3b3aeb95254433821a94f695b39550d4c46528a")

	decoder, err := NewDecoder()
	if err != nil {
		t.Fatal(err)
	}
	defer decoder.Close()

	template, err := decoder.Decode(decodeWALRecord(ProtocolNetFlow9, netFlowV9GoFlow2TemplateFixture))
	if err != nil {
		t.Fatal(err)
	}
	if !template.TemplateChanged || !template.CollectStateChanged || template.ObservationDomainID != 256 || len(template.Records) != 0 {
		t.Fatalf("unexpected raw template result: %+v", template)
	}

	decoded, err := decoder.Decode(decodeWALRecord(ProtocolNetFlow9, netFlowV9GoFlow2DataFixture))
	if err != nil {
		t.Fatal(err)
	}
	if len(decoded.Records) != 1 || decoded.ObservationDomainID != 256 || decoded.DatagramSequence != 838987420 || decoded.SequenceIncrement != 1 {
		t.Fatalf("unexpected raw data result: %+v", decoded)
	}
	record := decoded.Records[0]
	if record.SrcIP != netip.MustParseAddr("198.38.120.222") || record.DstIP != netip.MustParseAddr("88.121.217.208") || record.SrcPort != 443 || record.DstPort != 15184 || record.IPProtocol != 6 || record.TCPFlags != 0x10 || record.InIf != 354 || record.OutIf != 304 || record.RawPackets != 1 || record.RawBytes != 1500 {
		t.Fatalf("unexpected raw fixture field mapping: %+v", record)
	}
}

func assertFixtureSHA256(t *testing.T, fixture []byte, expected string) {
	t.Helper()
	digest := sha256.Sum256(fixture)
	if hex.EncodeToString(digest[:]) != expected {
		t.Fatalf("fixture SHA-256 changed: got=%x want=%s", digest, expected)
	}
}
